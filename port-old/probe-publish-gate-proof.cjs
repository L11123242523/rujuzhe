/* 隔离目录执行真实门禁和发布入口；不联网、不使用真实发布凭据。 */
'use strict';
const fs = require('fs'), path = require('path'), cp = require('child_process');
const Gate = require('../tools/gate-proof.cjs');
const source = path.resolve(__dirname, '..');
const root = path.join(__dirname, '_probe-publish-proof-' + process.pid);
let total = 0;
const check = (ok, label) => { if (!ok) throw new Error(label); total++; console.log('✅ ' + label); };
const put = (f, value) => { const p = path.join(root, f); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, value); };
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const env = { ...process.env }; delete env.RUJUZHE_RELEASE_PREPARED;
const run = (f, args = [], extra = {}) => cp.spawnSync(process.execPath, [path.join(root, f), ...args], { cwd: root, env, encoding: 'utf8', timeout: 10000, ...extra });
const blocked = (fn, label) => { let failed = false; try { fn(); } catch (e) { failed = /门禁|凭据|未经|清单/.test(e.message); } check(failed, label); };
const deploy = () => run('port-old/deploy-with-v.mjs', ['--msg=说明.txt', '--files=game.html,assets/engine.js', '--dry']);
const proofFile = () => path.join(root, '.gate-pass.json');
try {
  if (fs.existsSync(root)) throw new Error('测试目录已存在，拒绝覆盖');
  for (const d of ['assets', 'data', 'vendor', '_relaytest/lib', 'tools', 'port-old/e2e']) fs.mkdirSync(path.join(root, d), { recursive: true });
  for (const f of ['tools/gate-proof.cjs', 'tools/gate-then.cjs', 'port-old/deploy-with-v.mjs', 'port-old/publish-api-item2.cjs', 'port-old/bump-asset-version.cjs', 'port-old/gen-gamefiles-manifest.cjs']) put(f, fs.readFileSync(path.join(source, f)));
  put('tools/check-no-new-books.cjs', 'process.exit(0);');
  put('port-old/run-gates-parallel.cjs', 'process.exit(0);');
  put('port-old/_writecheck.cjs', 'process.exit(0);');
  put('game.html', '<script src="assets/engine.js?v=7"></script><script src="assets/app.js?v=7"></script>');
  put('assets/engine.js', 'var 状态 = 1;'); put('assets/app.js', "fetch('data/cards.json?v=2');");
  put('query.html', '查询'); put('cards.js', 'var 卡表 = [];'); put('data/cards.json', '{}'); put('说明.txt', '隔离验证');
  const initialHtml = read('game.html');
  let r = deploy(); check(r.status !== 0 && /缺少有效的全量门禁凭据/.test(r.stderr) && read('game.html') === initialHtml, '无凭据在升版前阻断');
  r = run('port-old/publish-api-item2.cjs', ['--msg=说明.txt', 'game.html']);
  check(r.status !== 0 && /门禁凭据/.test(r.stderr) && !/gh_token/.test(r.stderr), '底层上传也在读取凭据或联网前阻断');
  r = run('tools/gate-then.cjs'); check(r.status === 0 && fs.existsSync(proofFile()), '真实门禁入口仅全绿后生成凭据');
  check(Gate.verify(root, false).size === 0, '相同输入接受凭据');
  r = deploy(); check(r.status === 0 && read('game.html') === initialHtml, '有效凭据的空跑通过且不改盘');
  r = run('port-old/deploy-with-v.mjs', ['--msg=说明.txt', '--files=说明.txt', '--dry']);
  check(r.status !== 0 && /未经本次门禁/.test(r.stderr) && read('game.html') === initialHtml, '发布列表未覆盖文件在升版前阻断');
  const engine = read('assets/engine.js'); put('assets/engine.js', engine + '\n变更');
  blocked(() => Gate.verify(root, false), '验证后修改引擎，凭据失效');
  r = deploy(); check(r.status !== 0 && /输入已变化/.test(r.stderr) && read('game.html') === initialHtml, '发布入口拒绝验证后修改的文件');
  r = run('port-old/publish-api-item2.cjs', ['--msg=说明.txt', 'game.html']);
  check(r.status !== 0 && /输入已变化/.test(r.stderr), '直接调用上传器不能绕过文件变化检查');
  put('assets/engine.js', engine);
  put('assets/新增.js', '新资源'); blocked(() => Gate.verify(root, false), '新增运行资源使凭据失效'); fs.unlinkSync(path.join(root, 'assets/新增.js'));
  fs.renameSync(path.join(root, 'assets/engine.js'), path.join(root, '暂存.txt'));
  blocked(() => Gate.verify(root, false), '删除运行资源使凭据失效'); fs.renameSync(path.join(root, '暂存.txt'), path.join(root, 'assets/engine.js'));
  const oldProof = read('.gate-pass.json'); let proof = JSON.parse(oldProof); proof.node = '无效版本'; put('.gate-pass.json', JSON.stringify(proof));
  blocked(() => Gate.verify(root, false), '运行环境不同拒绝旧凭据'); put('.gate-pass.json', oldProof);
  blocked(() => Gate.verify(root, false, ['说明.txt']), '凭据未覆盖的发布文件被拒绝');
  blocked(() => Gate.verify(root, true, ['game.html']), '准备发布模式不能跳过规定的升版');
  r = run('port-old/bump-asset-version.cjs'); check(r.status === 0, '执行真实升版脚本');
  check(Gate.verify(root, true, ['game.html', 'assets/engine.js']).size === 2, '只接受规定的一次升版');
  const preparedHtml = read('game.html'); r = deploy();
  check(r.status === 0 && /继续同一版本/.test(r.stdout) && read('game.html') === preparedHtml, '已准备的发布可重试且不重复升版');
  put('game.html', read('game.html') + '意外修改'); blocked(() => Gate.verify(root, true), '升版之外的页面改动仍被拒绝');
  put('game.html', initialHtml); run('port-old/bump-asset-version.cjs');
  r = run('port-old/gen-gamefiles-manifest.cjs', ['--write']); check(r.status === 0, '执行真实清单生成脚本');
  check(Gate.verify(root, true, ['game.html', 'gamefiles.json']).size === 2, '自动清单与批准文件完全一致才可发布');
  const manifest = read('gamefiles.json'); let m = JSON.parse(manifest); m.files['assets/engine.js'] = '错误哈希'; put('gamefiles.json', JSON.stringify(m));
  blocked(() => Gate.verify(root, true, ['gamefiles.json']), '错误清单被拒绝'); put('gamefiles.json', manifest);
  run('port-old/bump-asset-version.cjs'); blocked(() => Gate.verify(root, true), '重复升版不能复用旧凭据'); put('game.html', initialHtml);
  const app = read('assets/app.js'); run('port-old/bump-asset-version.cjs'); put('assets/app.js', app.replace('?v=2', '?v=3'));
  check(Gate.verify(root, true, ['data/cards.json', 'assets/app.js']).size === 2, '发母本时只允许规定的fetch缓存键升级');
  blocked(() => Gate.verify(root, true, ['assets/app.js']), '未发母本不得擅改fetch键'); put('assets/app.js', app); put('game.html', initialHtml);
  // 上传替身只记录参数并模拟网络失败，完整执行真实发布入口的准备和重试流程。
  put('port-old/publish-api-item2.cjs', "const fs=require('fs');fs.writeFileSync('已尝试.json',JSON.stringify(process.argv.slice(2)));process.exit(1);");
  r = run('tools/gate-then.cjs'); check(r.status === 0, '为重试场景取得隔离门禁凭据');
  const args = ['--msg=说明.txt', '--files=data/cards.json'];
  r = run('port-old/deploy-with-v.mjs', args);
  check(r.status !== 0 && JSON.parse(read('已尝试.json')).includes('assets/app.js'), '模拟上传失败，母本首次发布自动带上app.js');
  const retryHtml = read('game.html'), retryApp = read('assets/app.js');
  r = run('port-old/deploy-with-v.mjs', args);
  check(r.status !== 0 && /继续同一版本/.test(r.stdout) && read('game.html') === retryHtml && read('assets/app.js') === retryApp && JSON.parse(read('已尝试.json')).includes('assets/app.js'), '模拟失败后原命令重试：版本与fetch键不重复升级，仍带上app.js');
  put('port-old/run-gates-parallel.cjs', 'process.exit(1);');
  r = run('tools/gate-then.cjs'); check(r.status !== 0 && !fs.existsSync(proofFile()), '门禁红灯清除上次凭据');
  put('port-old/run-gates-parallel.cjs', "require('fs').appendFileSync('assets/engine.js','变更');process.exit(0);");
  r = run('tools/gate-then.cjs'); check(r.status !== 0 && !fs.existsSync(proofFile()) && /输入已变化/.test(r.stderr), '门禁运行中输入变化，不得签发凭据');
  console.log('共 ' + total + ' 项，通过 ' + total + '，失败 0');
} finally {
  const resolved = path.resolve(root);
  if (path.dirname(resolved) !== __dirname || !path.basename(resolved).startsWith('_probe-publish-proof-')) throw new Error('清理路径超出本探针的隔离目录');
  fs.rmSync(resolved, { recursive: true, force: true });
}
